package dev.triumphteam.cmd.core.message;

import dev.triumphteam.cmd.core.message.context.MessageContext;
import org.jspecify.annotations.NonNull;

/**
 * Functional interface to allow simple message registering without the use of any hard coded data.
 *
 * @param <S> The command sender type.
 * @param <C> The {@link MessageContext} type.
 */
@FunctionalInterface
public interface MessageResolver<S, C extends MessageContext> {

    /**
     * Resolves the message, in most cases it'll send the message to the sender.
     *
     * @param sender  The command sender.
     * @param context The {@link MessageContext} generated by the command executor.
     */
    void resolve(@NonNull final S sender, @NonNull final C context);

}